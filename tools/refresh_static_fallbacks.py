"""Regenerate the static ESPN fallbacks (``rosters.py`` and ``schedule.csv``).

The live ESPN client is the source of truth whenever credentials are present;
these files are only consulted when that fetch is unavailable. They still need
to reflect the current season, otherwise a failed fetch silently falls back to
the previous year's league.

Usage (from the repository root):

    python tools/refresh_static_fallbacks.py [--season 2026]
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--season", type=int, default=None, help="Season to pull (defaults to ESPN_SEASON / DEFAULT_SEASON).")
    args = parser.parse_args()

    if args.season is not None:
        os.environ["ESPN_SEASON"] = str(args.season)

    import espn_client

    rosters, league = espn_client.fetch_rosters_from_espn()
    season = league.season
    print(f"Fetched season {season}: {len(rosters)} teams, "
          f"{sum(len(v) for groups in rosters.values() for v in groups.values())} players")

    # --- rosters.py -------------------------------------------------------
    lines = [
        "# Auto-generated by tools/refresh_static_fallbacks.py -- do not edit by hand.",
        f"# Static fallback rosters for the {season} season, used only when the live",
        "# ESPN fetch is unavailable. Re-run the script after trades or waiver moves.",
        "",
        "Fantasy_Rosters = {",
        "",
    ]
    for slug, groups in rosters.items():
        lines.append(f"  {slug!r}: {{")
        for pos in espn_client.PRIMARY_POSITIONS:
            players = groups.get(pos) or []
            rendered = ", ".join(repr(name) for name in players)
            lines.append(f"    {pos!r}: [{rendered}],")
        lines.append("  },")
        lines.append("")
    lines.append("}")
    lines.append("")
    (REPO_ROOT / "rosters.py").write_text("\n".join(lines))
    print("wrote rosters.py")

    # --- schedule.csv -----------------------------------------------------
    schedule = espn_client.league_schedule_to_dataframe(league)
    schedule.to_csv(REPO_ROOT / "schedule.csv", index=False)
    print(f"wrote schedule.csv ({len(schedule)} matchups)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
